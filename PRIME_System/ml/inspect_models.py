"""Inspect the team's pickled models and write ml/MODEL_REPORT.md (task T0.4).

Usage (from repo root):  python ml/inspect_models.py [models_dir] [raw_xlsx]
Loads ONLY the team's own files (pickles execute code on load).
"""
from __future__ import annotations

import hashlib
import json
import platform
import sys
import time
import warnings
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MODELS = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "ml_models"
RAW = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "raw_data" / "raw.xlsx"
FEATURES = ["Flow", "Motor Power", "Temperature (C)"]


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def features_from_raw(df: pd.DataFrame) -> pd.DataFrame:
    return pd.DataFrame({
        "Flow": df["Speed"] * df["SLL_Width"] * df["SLL_Height"],
        "Motor Power": df["Duty (%)"] * df["Voltage (V)"] * df["AbsCurrent (Amp)"],
        "Temperature (C)": df["Temperature (C)"],
    })


def main() -> None:
    import sklearn
    import xgboost

    lines: list[str] = []
    w = lines.append
    w("# MODEL_REPORT: PRIME ML models (generated by `ml/inspect_models.py`)\n")
    w(f"Generated: {time.strftime('%Y-%m-%d %H:%M')} · Python {platform.python_version()} · "
      f"scikit-learn {sklearn.__version__} · xgboost {xgboost.__version__} · numpy {np.__version__}\n")

    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        xgb = joblib.load(MODELS / "xgb_extrusion_model.pkl")
        rf = joblib.load(MODELS / "rf_delay_model.pkl")
    load_warnings = sorted({str(c.message).splitlines()[0][:160] for c in caught
                            if not issubclass(c.category, ResourceWarning)})

    xinfo = joblib.load(MODELS / "xgb_extrusion_deployment_info.pkl")
    rinfo = joblib.load(MODELS / "rf_delay_deployment_info.pkl")
    xfeat = list(joblib.load(MODELS / "xgb_extrusion_features.pkl"))
    rfeat = list(joblib.load(MODELS / "rf_delay_features.pkl"))
    rf_bytes = (MODELS / "rf_delay_model.pkl").read_bytes()[:2_000_000]
    i = rf_bytes.find(b"_sklearn_version")
    trained_sklearn = rf_bytes[i + 19:i + 30].split(b"\x94")[0].decode(errors="ignore") if i >= 0 else "?"

    w("## 1. Files\n")
    w("| File | Size | SHA-256 (first 16) |\n|---|---|---|")
    for p in sorted(MODELS.glob("*.pkl")):
        w(f"| `{p.name}` | {p.stat().st_size / 1e6:.2f} MB | `{sha256(p)[:16]}` |")
    w("")

    w("## 2. Models\n")
    w("| | Extrusion model | Interlayer-delay model |\n|---|---|---|")
    w(f"| Class | `{type(xgb).__module__}.{type(xgb).__name__}` | `{type(rf).__module__}.{type(rf).__name__}` |")
    w(f"| Deployment name | {xinfo['Model Name']} | {rinfo['Model Name']} |")
    w(f"| Output | {xinfo['Output']} (regression) | {rinfo['Output']}, **classes {list(map(int, rf.classes_))}** (treated as minutes) |")
    w(f"| Feature order (from `*_features.pkl`) | {xfeat} | {rfeat} |")
    w(f"| `feature_names_in_` / booster names | {xgb.get_booster().feature_names} | {list(rf.feature_names_in_)} |")
    w(f"| Size | n_estimators={xgb.get_params()['n_estimators']}, max_depth={xgb.get_params()['max_depth']}, lr={xgb.get_params()['learning_rate']:.4f} | n_estimators={rf.n_estimators}, max_depth={rf.max_depth} |")
    w(f"| Trained with | xgboost version not stored in pickle (loads in {xgboost.__version__} with a warning) | scikit-learn {trained_sklearn} (from pickle) |")
    w(f"| Feature importance | {dict((k, round(float(v), 3)) for k, v in zip(xfeat, xgb.feature_importances_))} | {dict(zip(rfeat, np.round(rf.feature_importances_, 3).tolist()))} |")
    w("")
    w("**Load warnings:** " + ("; ".join(load_warnings) if load_warnings else "none"))
    w("")

    w("## 3. Feature engineering (confirmed by Kasra, Nov 20 2026)\n")
    w("| Feature | Formula | Unit / typical value in lab data |\n|---|---|---|")
    w("| `Flow` | **speed × SLL_Width × SLL_Height** | mm/s × mm × mm = mm³/s, ~2,600–3,200 |")
    w("| `Motor Power` | **Duty × Voltage × Current** | W (negative sign from duty convention), ~ −0.8 to −5.6 |")
    w("| `Temperature (C)` | material temperature | °C, 15.9–16.7 in raw.xlsx |")
    w("\n> `*_deployment_info.pkl` says Flow uses *Total Height*; the team confirmed **SLL_Height** is correct. The backend uses SLL_Height.\n")

    raw = pd.read_excel(RAW)
    X = features_from_raw(raw)
    t0 = time.perf_counter(); px = xgb.predict(X[xfeat]); tx = (time.perf_counter() - t0) * 1000
    t0 = time.perf_counter(); pp = rf.predict_proba(X[rfeat]); tr = (time.perf_counter() - t0) * 1000
    w("## 4. Smoke test on `data/raw/raw.xlsx` (20 rows, 5 layers)\n")
    tab = X.assign(**{"RPM (actual)": raw["Extrusion Rate (RPM)"], "XGB RPM": px.round(1),
                      "Delay (actual)": raw["Delay"], "RF delay": rf.classes_[pp.argmax(1)],
                      "RF conf": pp.max(1).round(2)}).round(2)
    w(tab.to_markdown(index=False))
    mae = float(np.mean(np.abs(px - raw["Extrusion Rate (RPM)"])))
    acc = float(np.mean(rf.classes_[pp.argmax(1)] == raw["Delay"]))
    w(f"\nXGB MAE vs actual RPM: **{mae:.1f} RPM**. RF accuracy vs actual delay: **{acc:.0%}** "
      f"(this sheet is all 5 min at ~16 °C, a region where the RF says 1 min).")
    w(f"Inference time for 20 rows: XGB {tx:.1f} ms, RF {tr:.0f} ms.\n")

    w("## 5. Response map at Flow ≈ 3,050 (lab geometry)\n")
    w("Cell = `RF delay class / XGB RPM`. Rows = temperature (°C), columns = motor power (W).\n")
    temps = np.round(np.arange(15.0, 23.6, 0.5), 1)
    powers = np.round(np.arange(-0.5, -7.01, -0.5), 1)
    grid = pd.DataFrame([(3050.0, p, t) for t in temps for p in powers], columns=FEATURES)
    gx = xgb.predict(grid).round(0).astype(int)
    gc = rf.classes_[rf.predict_proba(grid).argmax(1)]
    grid["cell"] = [f"{c}/{r}" for c, r in zip(gc, gx)]
    w(grid.pivot(index="Temperature (C)", columns="Motor Power", values="cell").to_markdown())
    w("")
    w("## 6. Findings that shape the demo\n")
    w("1. Both models load with scikit-learn 1.8.0; the XGBoost pickle loads with a newer xgboost "
      "(warning only). Recommended: re-export with `model.get_booster().save_model('xgb_extrusion.json')` "
      "from the training environment for long-term safety; the adapter accepts `.json` too.")
    w("2. **XGBoost RPM is driven mostly by Motor Power** at lab flow (−1 W → ~15 RPM, −2.5 W → ~27–36 RPM, −4.5 W → ~45–65 RPM).")
    w("3. **The RF delay class is driven mostly by Temperature**: ≤ 18.5 °C → 1 min; ~19.5–20 °C → 10 min "
      "(when |power| < ~3 W); ~21.5–23 °C → 5 min. Confidences are moderate (0.5–0.85).")
    w("4. The models are step-like (tree ensembles), so the demo datasets in `data/generated/` were synthesized "
      "around the lab ranges and **checked against these exact models** (`data/generator/generate_datasets.py`).")
    w("5. RF confidence = max class probability (`predict_proba`), shown in the UI as the AI confidence.")
    out = ROOT / "ml" / "MODEL_REPORT.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
